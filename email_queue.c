int main() {                                                           // Main function entry point[cite: 8]
    char buffer[256];                                                  // Character array buffer to hold incoming lines of text[cite: 8]
    while (fgets(buffer, sizeof(buffer), stdin) != NULL) {             // Loop to read standard input line by line until EOF[cite: 8]
        buffer[strcspn(buffer, "\r\n")] = 0;                           // Strip newline and carriage return characters from the buffer[cite: 8]
        if (strncmp(buffer, "EMAIL ", 6) == 0) {                       // Check if the command starts with 'EMAIL '[cite: 9]
            char *category = strtok(buffer + 6, ",");                  // Extract the category string before the first comma[cite: 8]
            char *subject = strtok(NULL, ",");                         // Extract the subject string before the second comma[cite: 8]
            char *date = strtok(NULL, "");                             // Extract the remainder of the string as the date[cite: 8]
            if (category && subject && date) {                         // Verify all three fields were successfully parsed[cite: 8]
                while(*subject == ' ') subject++;                      // Trim leading spaces from the subject[cite: 8]
                while(*date == ' ') date++;                            // Trim leading spaces from the date[cite: 8]
                insert_email(category, subject, date);                 // Insert the parsed data into the MaxHeap priority queue[cite: 8]
            }                                                          // End of inner if statement[cite: 8]
        } else if (strcmp(buffer, "NEXT") == 0) {                      // Check if the command is exactly 'NEXT'[cite: 9]
            peek_max();                                                // Display the highest priority email without removing it[cite: 8]
        } else if (strcmp(buffer, "READ") == 0) {                      // Check if the command is exactly 'READ'[cite: 9]
            extract_max();                                             // Remove the highest priority email from the queue[cite: 8]
        } else if (strcmp(buffer, "COUNT") == 0) {                     // Check if the command is exactly 'COUNT'[cite: 9]
            printf("There are %d emails to read.\n", heap_size);       // Print the current total number of emails in the heap[cite: 9]
        }                                                              // End of else-if chain[cite: 8]
    }                                                                  // End of while loop[cite: 8]
    return 0;                                                          // Return 0 to indicate successful program execution[cite: 8]
} // End of main function[cite: 8]